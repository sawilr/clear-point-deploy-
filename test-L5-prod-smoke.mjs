// L5 — ONE-SHOT PRODUCTION SMOKE TEST
// Single POST to https://clearpointsenioradvisors.com/api/submit-lead
// Clearly marked test data; Sawil will delete the resulting GHL contact.
// No tokens read. No env values accessed. No code changes. No deploy.

const ENDPOINT = 'https://clearpointsenioradvisors.com/api/submit-lead';

const payload = {
  // Names obviously marked for safe deletion
  first_name: 'L5QA-Prod-Smoke',
  last_name: 'SafeToDelete-20260524',

  // Valid US phone format: area code 212 (NYC, valid), exchange 555 (reserved fictional),
  // subscriber 0100 (within RFC-reserved 555-01XX fictional range used by film/TV).
  phone: '2125550100',

  // RFC 2606 reserved .invalid TLD — will never reach a real inbox.
  email: 'l5qa-prod-smoke@example.invalid',

  preferred_language: 'en',
  zip: '10001',
  city: 'New York',
  derived_state: 'NY',
  state: 'NY',
  medicare_status: 'Original Medicare (Parts A & B)',

  // Consent flags set true (this is a system smoke test, not a real lead)
  consent_to_contact: true,
  consent: true,
  consent_sms: true,
  consent_call: true,

  lead_notes:
    '[L5 QA PRODUCTION SMOKE TEST — SAFE TO DELETE] ' +
    'Generated by Claude L5 verification on 2026-05-24 to confirm production /api/submit-lead is alive. ' +
    'No real person. No real contact info. Phone is RFC-reserved fictional. Email is RFC-reserved .invalid TLD. ' +
    'Delete this contact at your convenience.',
  conversation_summary: 'L5 QA Production Smoke Test. Confirms endpoint health and GHL ingest path.',

  lead_source: 'L5 QA Production Smoke Test',
  form_name: 'L5 QA Production Smoke Test',
  tags: ['L5QA', 'Smoke Test', 'Safe To Delete'],

  created_at: new Date().toISOString(),
};

console.log('=== L5 PRODUCTION SMOKE TEST ===');
console.log(`Endpoint:  ${ENDPOINT}`);
console.log(`Test name: ${payload.first_name} ${payload.last_name}`);
console.log(`Phone:     ${payload.phone.slice(0, 3)}-***-${payload.phone.slice(-4)} (fictional)`);
console.log(`Email:     ${payload.email.replace(/^([^@]).*(@)/, '$1***$2')}`);
console.log('');

const start = Date.now();
let result;
try {
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  });
  const text = await res.text();
  let json = null;
  try { json = JSON.parse(text); } catch {}
  result = {
    status: res.status,
    ok: res.ok,
    response: json || text.slice(0, 500),
    durationMs: Date.now() - start,
  };
} catch (err) {
  result = {
    status: 'NETWORK_ERROR',
    ok: false,
    response: err && err.message ? err.message : String(err),
    durationMs: Date.now() - start,
  };
}

console.log('=== RESULT ===');
console.log(`Status:     ${result.status}`);
console.log(`OK:         ${result.ok}`);
console.log(`Duration:   ${result.durationMs}ms`);
console.log(`Response:   ${JSON.stringify(result.response)}`);
console.log('');

if (result.status === 200 && result.response && result.response.contact_id) {
  console.log(`✅ PASS — GHL contact created: ${result.response.contact_id}`);
  console.log(`   Sawil: delete this contact in GHL when convenient.`);
} else if (result.status === 400) {
  console.log(`⚠️  Validation rejected — check payload or area-code allow-list`);
} else if (result.status === 500) {
  console.log(`❌ Server error — env config issue on production?`);
} else if (result.status === 502) {
  console.log(`❌ Upstream CRM error — GHL rejected the contact`);
} else {
  console.log(`❓ Unexpected status — see response above`);
}
